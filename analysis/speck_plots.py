def plot_single_line(data, out_base: Path, annotate_count: int):
    keys = [k for k, _ in data]
    y = [v for _, v in data]
    x = list(range(len(data)))
    x_labels = [format_shift_label(a, b) for a, b in keys]

    # 自动根据点数量扩展宽度，保持高度不变（4.8）以避免横坐标重叠
    width = max(6.4, min(20.0, len(x) * 0.25))
    fig, ax = plt.subplots(figsize=(width, 4.8))
    ax.plot(x, y, marker="o", linewidth=1.8, markersize=6)
    ax.set_xlabel("Bit index k (diff = 1 << k)", fontsize=18)
    ax.set_ylabel("Value", fontsize=18)
    ax.set_xticks(x)
    ax.set_xticklabels(x_labels, rotation=90, fontsize=14)
    ax.tick_params(axis='both', labelsize=14)
    ax.grid(alpha=0.25, linewidth=0.6)

    y_min = min(y)
    ax.set_ylim(y_min - 3, max(y) + 3)

    min_indices = [i for i, v in enumerate(y) if v == y_min]
    chosen = min_indices[:annotate_count]
    if annotate_count == 2 and len(min_indices) < 2:
        chosen = sorted(range(len(y)), key=lambda i: (y[i], i))[:2]

    offsets = [(-85, 5), (80, 5)]
    for j, idx in enumerate(chosen):
        text = f"{format_hex_pair(keys[idx])}\n{y[idx]:.1f}"
        dx, dy = offsets[j] if j < len(offsets) else (0, -40)
        add_box_annotation(ax, idx, y[idx], text, dx=dx, dy=dy)

    fig.tight_layout()
    save_figure(fig, out_base)



def plot_three_lines(data_main, data_aux, out_base: Path, aux_label: str):
    main_map = dict(data_main)
    aux_map = dict(data_aux)
    keys = [k for k, _ in data_main]

    y1 = [main_map[k] for k in keys]
    y2 = [aux_map[k] for k in keys]
    y3 = [main_map[k] + aux_map[k] for k in keys]

    x = list(range(len(keys)))
    x_labels = [format_shift_label(a, b) for a, b in keys]

    fig, ax = plt.subplots(figsize=(6.4, 4.8))
    ax.plot(x, y1, marker="o", linewidth=2.0, markersize=4, label="forward weight")
    ax.plot(x, y2, marker="s", linewidth=2.0, markersize=4, label="backward weight")
    ax.plot(x, y3, marker="^", linewidth=2.2, markersize=5, label=f"combined weight")


    max_xticks = 18
    step = max(1, int(np.ceil(len(x) / max_xticks)))
    tick_idx = list(range(0, len(x), step))
    if tick_idx[-1] != len(x) - 1:
        tick_idx.append(len(x) - 1)

    ax.set_xticks([x[i] for i in tick_idx])
    ax.set_xticklabels([x_labels[i] for i in tick_idx], rotation=90, fontsize=14)
    ax.set_xlabel("Bit index k (diff = 1 << k)", fontsize=18)
    ax.set_ylabel("Value", fontsize=18)
    ax.tick_params(axis='both', labelsize=14)
    ax.grid(alpha=0.25, linewidth=0.6)
    ax.legend(fontsize=12, loc='best', framealpha=0.8)

    all_vals = np.array(y1 + y2 + y3, dtype=float)
    ax.set_ylim(np.min(all_vals) - 4, np.max(all_vals) + 6)

    min_idx = int(np.argmin(y3))
    text = f"{format_hex_pair(keys[min_idx])}\n{y3[min_idx]:.1f}"
    add_box_annotation(ax, min_idx, y3[min_idx], text, dx=30, dy=-55)

    fig.tight_layout()
    save_figure(fig, out_base)


