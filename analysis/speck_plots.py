def get_bit_position(n: int) -> int:
    if n == 0:
        return -1
    return int(math.log2(n & -n))


def format_shift_label(a: int, b: int) -> str:
    pos_a = get_bit_position(a)
    pos_b = get_bit_position(b)
    if a != 0 and b == 0:
        return f"L{pos_a}"
    if a == 0 and b != 0:
        return f"R{pos_b}"
    if a == 0 and b == 0:
        return "-"
    return f"L{pos_a},R{pos_b}"


def format_hex_pair(key: tuple[int, int]) -> str:
    a, b = key
    return f"(0x{a:x}, 0x{b:x})"


def add_box_annotation(ax, x, y, text, dx=0, dy=55):
    ax.annotate(
        text,
        xy=(x, y),
        xytext=(dx, dy),
        textcoords="offset points",
        ha="center",
        va="top",
        bbox=dict(boxstyle="round,pad=0.35", fc="#fff433", ec="red", lw=1.4),
        arrowprops=dict(arrowstyle="->", color="red", lw=1.4),
    )


def save_figure(fig, out_base: Path):
    fig.savefig(out_base.with_suffix(".png"), dpi=400, bbox_inches="tight")
    fig.savefig(out_base.with_suffix(".pdf"), bbox_inches="tight")
    plt.close(fig)


