def get_bit_position(n: int) -> int:
    if n == 0:
        return -1
    return int(math.log2(n & -n))


def format_shift_label(a: int, b: int) -> str:
    pos_a = get_bit_position(a)
    pos_b = get_bit_position(b)
    if a != 0 and b == 0:
        return f"L{pos_a}"
    if a == 0 and b != 0:
        return f"R{pos_b}"
    if a == 0 and b == 0:
        return "-"
    return f"L{pos_a},R{pos_b}"


def format_hex_pair(key: tuple[int, int]) -> str:
    a, b = key
    return f"(0x{a:x}, 0x{b:x})"


