def plot_speck96_compare(out_base: Path):
    main_keys = [k for k, _ in data1]
    map2 = dict(data2)
    map3 = dict(data3)
    map4 = dict(data4)

    y1 = [v for _, v in data1]
    y2 = [map2.get(k, np.nan) for k in main_keys]
    y3 = [map3.get(k, np.nan) for k in main_keys]
    y4 = [map4.get(k, np.nan) for k in main_keys]

    x = list(range(len(main_keys)))
    x_labels = [format_shift_label(a, b) for a, b in main_keys]

    fig, ax = plt.subplots(figsize=(6.4, 4.8))
    ax.plot(x, y1, marker="o", linewidth=2.0, markersize=4, label="EGBS")
    ax.plot(x, y2, marker="s", linewidth=2.0, markersize=4, label="BS")
    ax.plot(x, y3, marker="^", linewidth=2.0, markersize=4, label="BS + SP")
    ax.plot(x, y4, marker="d", linewidth=2.0, markersize=4, label="BS + GA")

    max_xticks = 18
    step = max(1, int(np.ceil(len(x) / max_xticks)))
    tick_idx = list(range(0, len(x), step))
    if tick_idx[-1] != len(x) - 1:
        tick_idx.append(len(x) - 1)

    ax.set_xticks([x[i] for i in tick_idx])
    ax.set_xticklabels([x_labels[i] for i in tick_idx], rotation=90)
    ax.set_xlabel("Bit index k (single-bit input difference)")
    ax.set_ylabel("Value")
    ax.grid(alpha=0.25, linewidth=0.6)
    ax.legend()

    all_vals = np.asarray(y1 + y2 + y3 + y4, dtype=float)
    finite_vals = all_vals[np.isfinite(all_vals)]
    ax.set_ylim(float(np.min(finite_vals)) - 4, float(np.max(finite_vals)) + 6)

    min_idx = int(np.argmin(np.asarray(y1, dtype=float)))
    text = f"{format_hex_pair(main_keys[min_idx])}\n{y1[min_idx]:.1f}"
    # add_box_annotation(ax, min_idx, y1[min_idx], text, dx=0, dy=45, va="bottom")

    fig.tight_layout()
    save_figure(fig, out_base)


